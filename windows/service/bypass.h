#ifndef SERVICE_BYPASS_H_
#define SERVICE_BYPASS_H_

#include <functional>
#include <string>
#include <utility>
#include <vector>

// Программы с пометкой «Напрямую» — мимо ядра VPN.
//
// Адаптер VPN забирает весь трафик, и ядро уже само решает, куда его отправить: даже то, что идёт
// «напрямую», проходит через ядро. Чтобы пакеты таких программ (игр) в ядро не попадали, служба следит за
// отправкой UDP в Windows (события Microsoft-Windows-Kernel-Network: номер процесса и адрес назначения)
// и для каждого адреса, куда шлёт программа из списка, ставит маршрут сразу в сетевую карту, мимо
// адаптера. Первые пакеты успевают пройти через ядро — оно и так отправляет их напрямую.
//
// Подсети, которые программа запомнила по прошлым подключениям, получают маршрут сразу при запуске — до
// первого пакета: тогда и «подключённый» сокет UDP (connect), который Windows привязывает к адаптеру
// навсегда, с самого начала идёт мимо.
//
// Маршрут действует на адрес целиком: туда же напрямую пойдут и другие программы. Ставятся только
// маршруты IPv4 к адресам в интернете (не к локальной сети). В Windows они живут до перезагрузки, поэтому
// служба записывает их в [state_file] и убирает при остановке, а после сбоя — при следующем запуске.

// Подсеть IPv4: адрес (порядок байт сети) и длина префикса.
using BypassNet = std::pair<unsigned long, unsigned char>;

// Начать. |tun_v4| — адрес адаптера VPN (его маршрут по умолчанию не берётся), |rules| — правила программ
// в виде правил ядра: имя процесса (с .exe или без), полный путь или папка с «/» в конце, прямые слэши.
// |preload| — подсети, к которым маршрут ставится сразу.
// |before_route| вызывается перед каждым новым маршрутом — Kill Switch успевает его разрешить; false —
// маршрут не ставится. |on_route| — после маршрута к новому адресу: адрес, имя exe и правило, под которое
// программа подошла (в том виде, как его прислали). |on_stuck| — программа и после маршрута шлёт к адресу
// через адаптер: её сокет UDP привязан к адаптеру (connect), это соединение до закрытия идёт через ядро.
// Один раз на программу и адрес. Пустая строка — следим; иначе причина отказа.
std::wstring BypassStart(const std::wstring& session_name, const std::wstring& tun_v4,
                         const std::vector<std::wstring>& rules, const std::vector<BypassNet>& preload,
                         const std::wstring& state_file, std::function<bool(const BypassNet&)> before_route,
                         std::function<void(unsigned long, const std::wstring&, const std::wstring&)> on_route,
                         std::function<void(unsigned long, const std::wstring&)> on_stuck);

// Перестать следить и убрать поставленные маршруты. Безопасно вызывать, когда не начато.
void BypassStop();

// Подсети (и отдельные адреса — /32), к которым сейчас стоят маршруты.
std::vector<BypassNet> BypassNets();

// Подсеть в интернете с префиксом от /16 до /32 — её можно пустить мимо адаптера.
bool BypassNetOk(const BypassNet& net);

// Убрать маршруты, оставшиеся после сбоя службы (записаны в |state_file|).
void BypassCleanupStale(const std::wstring& state_file);

#endif  // SERVICE_BYPASS_H_
